import random

import matplotlib.pyplot as plt
import numpy as np
import torch
import torch.nn as nn
from opacus import PrivacyEngine
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms

SEED = 42
N_TRAIN = 20_000
EPOCHS = 3
BATCH_SIZE = 256
LR = 1e-3
DELTA = 1e-5
MAX_GRAD_NORM = 1.0
TARGET_EPSILONS = [10.0, 5.0, 1.0]
FIXED_NOISE = 1.1
MAX_ACCEPTABLE_DROP_PP = 5.0


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


set_seed(SEED)
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("device:", DEVICE)

transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.1307,), (0.3081,)),
])

train_full = datasets.MNIST(root="./data", train=True, download=True, transform=transform)
test_ds = datasets.MNIST(root="./data", train=False, download=True, transform=transform)

subset_gen = torch.Generator().manual_seed(SEED)
subset_idx = torch.randperm(len(train_full), generator=subset_gen)[:N_TRAIN].tolist()
train_ds = Subset(train_full, subset_idx)

test_loader = DataLoader(test_ds, batch_size=512, shuffle=False, num_workers=0)
train_eval_loader = DataLoader(train_ds, batch_size=512, shuffle=False, num_workers=0)

print(f"train subset: {len(train_ds)}   test: {len(test_ds)}")


def make_train_loader():
    return DataLoader(
        train_ds,
        batch_size=BATCH_SIZE,
        shuffle=True,
        num_workers=0,
        generator=torch.Generator().manual_seed(SEED),
    )

class DigitCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 32, kernel_size=3, padding=1)
        self.gn1 = nn.GroupNorm(8, 32)
        self.conv2 = nn.Conv2d(32, 64, kernel_size=3, padding=1)
        self.gn2 = nn.GroupNorm(8, 64)
        self.pool = nn.MaxPool2d(2)
        self.fc1 = nn.Linear(64 * 7 * 7, 128)
        self.fc2 = nn.Linear(128, 10)

    def forward(self, x):
        x = self.pool(torch.relu(self.gn1(self.conv1(x))))
        x = self.pool(torch.relu(self.gn2(self.conv2(x))))
        x = torch.flatten(x, 1)
        x = torch.relu(self.fc1(x))
        return self.fc2(x)


def prepare_run():
    set_seed(SEED)
    model = DigitCNN().to(DEVICE)
    optimizer = torch.optim.Adam(model.parameters(), lr=LR)
    loader = make_train_loader()
    return model, optimizer, loader


criterion = nn.CrossEntropyLoss()
n_params = sum(p.numel() for p in DigitCNN().parameters())
print(f"DigitCNN parameters: {n_params:,}")

def evaluate(model, loader):
    model.eval()
    correct = 0
    total = 0
    with torch.no_grad():
        for x, y in loader:
            x, y = x.to(DEVICE), y.to(DEVICE)
            pred = model(x).argmax(dim=1)
            correct += (pred == y).sum().item()
            total += y.size(0)
    return correct / total


def mean_max_softmax(model, loader):
    model.eval()
    total = 0.0
    count = 0
    with torch.no_grad():
        for x, _ in loader:
            x = x.to(DEVICE)
            probs = torch.softmax(model(x), dim=1)
            total += probs.max(dim=1).values.sum().item()
            count += x.size(0)
    return total / count


def fit(model, loader, optimizer, privacy_engine=None):
    eps_history = []
    for epoch in range(1, EPOCHS + 1):
        model.train()
        loss_sum = 0.0
        seen = 0
        for x, y in loader:
            if y.numel() == 0:
                continue
            x, y = x.to(DEVICE), y.to(DEVICE)
            optimizer.zero_grad()
            loss = criterion(model(x), y)
            loss.backward()
            optimizer.step()
            loss_sum += loss.item() * y.size(0)
            seen += y.size(0)
        acc = evaluate(model, test_loader)
        msg = f"  epoch {epoch}/{EPOCHS}  loss={loss_sum / max(seen, 1):.4f}  test_acc={acc * 100:.1f}%"
        if privacy_engine is not None:
            eps = privacy_engine.get_epsilon(delta=DELTA)
            eps_history.append(eps)
            msg += f"  eps={eps:.2f}"
        print(msg)
    return evaluate(model, test_loader), eps_history

"""### Non private baseline"""

print("Training baseline (no DP)")
baseline_model, baseline_opt, baseline_loader = prepare_run()
baseline_acc, _ = fit(baseline_model, baseline_loader, baseline_opt)
print(f"Baseline (no DP) : test accuracy {baseline_acc * 100:.1f} %")

"""## DP models at target ε = 10, 5 and 1"""

dp_results = []
model_eps1 = None

for target_eps in TARGET_EPSILONS:
    print(f"\nTraining DP model  target eps = {target_eps:g}")
    model, optimizer, loader = prepare_run()
    privacy_engine = PrivacyEngine()
    model, optimizer, loader = privacy_engine.make_private_with_epsilon(
        module=model,
        optimizer=optimizer,
        data_loader=loader,
        epochs=EPOCHS,
        target_epsilon=target_eps,
        target_delta=DELTA,
        max_grad_norm=MAX_GRAD_NORM,
    )
    noise = getattr(optimizer, "noise_multiplier", float("nan"))
    print(f"  calibrated noise_multiplier = {noise:.3f}")
    test_acc, eps_history = fit(model, loader, optimizer, privacy_engine)
    eps_spent = eps_history[-1]
    dp_results.append({
        "target_eps": target_eps,
        "test_acc": test_acc,
        "eps_spent": eps_spent,
        "noise_multiplier": noise,
    })
    if target_eps == 1.0:
        model_eps1 = model

print("\nDP sweep done")
for row in dp_results:
    print(
        f"  target {row['target_eps']:g}  "
        f"test_acc {row['test_acc'] * 100:.1f}%  "
        f"eps_spent {row['eps_spent']:.2f}"
    )

